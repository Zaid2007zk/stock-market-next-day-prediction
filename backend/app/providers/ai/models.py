"""
AI Research Assistant Data Models
Defines structured citations, grounded research briefs, and chat request/response schemas.
"""

from typing import List, Optional, Any, Dict
from datetime import datetime, timezone
from pydantic import BaseModel, Field


class Citation(BaseModel):
    """Verifiable data citation linked to a backend deterministic metric or filing."""
    metric_name: str = Field(..., description="Name of metric, e.g., 'RSI (14)', 'P/E Ratio', '52-Week High'")
    value: Any = Field(..., description="Exact numerical or categorical value")
    source: str = Field(..., description="Authoritative data source attribution")
    timestamp: str = Field(..., description="Timestamp of the cited data point")
    verified: bool = Field(default=True, description="True if validated against backend calculations")


class ResearchBriefResponse(BaseModel):
    """Structured research brief generated by the Financial Research Assistant."""
    symbol: str
    summary: str
    factor_analysis: str
    risk_notes: str
    citations: List[Citation] = Field(default_factory=list)
    uncertainty_notes: Optional[str] = Field(None, description="Explicit caveats if data is stale, unverified, or missing")
    is_fallback: bool = Field(default=False, description="True if generated by deterministic fallback engine")
    model_name: str = Field(default="Deterministic Synthesis Engine")
    generated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class ResearchChatRequest(BaseModel):
    """User query submitted to the Financial Research Assistant."""
    symbol: str = Field(..., description="Ticker symbol being researched")
    question: str = Field(..., min_length=2, max_length=500, description="User research question")


class ResearchChatResponse(BaseModel):
    """Assistant answer strictly grounded in backend deterministic metrics."""
    symbol: str
    answer: str
    citations: List[Citation] = Field(default_factory=list)
    uncertainty_notes: Optional[str] = None
    is_fallback: bool = False
    model_name: str
    generated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
